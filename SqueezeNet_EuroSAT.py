"""SqueezeNet 1.1 on the shared EuroSAT RGB splits.

Converted from SqueezeNet_EuroSAT.ipynb; no split is generated by this script.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def positive_int(value):
    value = int(value)
    if value < 1:
        raise argparse.ArgumentTypeError("must be at least 1")
    return value


def nonnegative_int(value):
    value = int(value)
    if value < 0:
        raise argparse.ArgumentTypeError("must be nonnegative")
    return value


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, help="Folder containing the ten EuroSAT class folders; otherwise download with kagglehub")
    parser.add_argument("--splits", type=Path, default=ROOT / "eurosat_splits.csv")
    parser.add_argument("--classes", type=Path, default=ROOT / "eurosat_classes.json")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "squeezenet_results")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--batch-size", type=positive_int, default=64)
    parser.add_argument("--num-workers", type=nonnegative_int, default=2)
    parser.add_argument("--head-epochs", type=positive_int, default=5)
    parser.add_argument("--fine-tune-epochs", type=positive_int, default=20)
    parser.add_argument("--show-plots", action="store_true")
    return parser.parse_args()


class EuroSATDataset:
    def __init__(self, manifest, split, root, transform):
        self.frame = (
            manifest[manifest["split"] == split]
            .reset_index(drop=True)
        )
        self.root = Path(root)
        self.transform = transform

    def __len__(self):
        return len(self.frame)

    def __getitem__(self, index):
        from PIL import Image

        row = self.frame.iloc[index]

        with Image.open(
            self.root / row["relative_path"]
        ) as image:
            image = image.convert("RGB")
            image = self.transform(image)

        label = int(row["label"])
        return image, label



def train(args):
    import json
    import time
    import random

    from pathlib import Path

    import numpy as np
    import pandas as pd
    import matplotlib
    if not args.show_plots:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    import torch
    from torch import nn
    from torch.utils.data import DataLoader

    import torchvision
    from torchvision import transforms
    from torchvision.models import (
        squeezenet1_1,
        SqueezeNet1_1_Weights
    )

    from PIL import Image
    from tqdm.auto import tqdm

    from sklearn.metrics import (
        accuracy_score,
        classification_report,
        confusion_matrix,
        ConfusionMatrixDisplay
    )


    SEED = args.seed

    random.seed(SEED)
    np.random.seed(SEED)
    torch.manual_seed(SEED)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(SEED)

    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

    device = torch.device(
        "cuda" if torch.cuda.is_available() else "cpu"
    )

    OUTPUT_DIR = args.output_dir
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print("Device:", device)
    print("PyTorch:", torch.__version__)
    print("Torchvision:", torchvision.__version__)

    from eurosat_data import load_splits, validate_images

    rows, class_names = load_splits(args.splits, args.classes)
    manifest = pd.DataFrame(rows)
    NUM_CLASSES = len(class_names)
    print(manifest["split"].value_counts())
    print("Classes:", class_names)


    if args.data_dir is None:
        import kagglehub
        dataset_path = kagglehub.dataset_download("apollo2506/eurosat-dataset")
        DATA_DIR = Path(dataset_path) / "EuroSAT"
    else:
        DATA_DIR = args.data_dir

    validate_images(rows, DATA_DIR)
    print("Dataset directory:", DATA_DIR)
    print("All manifest images found.")

    IMAGE_SIZE = (64, 64)
    BATCH_SIZE = args.batch_size

    # Preserve the notebook's preprocessing without augmentation.
    image_transform = transforms.Compose([
        transforms.Resize(
            IMAGE_SIZE,
            interpolation=transforms.InterpolationMode.BILINEAR
        ),
        transforms.ToTensor(),
        transforms.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225]
        )
    ])


    train_dataset = EuroSATDataset(
        manifest, "train", DATA_DIR, image_transform
    )
    val_dataset = EuroSATDataset(
        manifest, "val", DATA_DIR, image_transform
    )
    test_dataset = EuroSATDataset(
        manifest, "test", DATA_DIR, image_transform
    )

    generator = torch.Generator().manual_seed(SEED)

    train_loader = DataLoader(
        train_dataset,
        batch_size=BATCH_SIZE,
        shuffle=True,
        generator=generator,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda")
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda")
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda")
    )

    images, labels = next(iter(train_loader))

    print("Image batch:", images.shape)
    print("Label batch:", labels.shape)

    weights = SqueezeNet1_1_Weights.DEFAULT

    model = squeezenet1_1(weights=weights)

    # Freeze the pretrained feature extractor initially.
    for parameter in model.features.parameters():
        parameter.requires_grad = False

    # A new classifier produces one logit per EuroSAT class.
    # No softmax: CrossEntropyLoss works directly with logits.
    model.classifier = nn.Sequential(
        nn.Dropout(p=0.5),
        nn.Conv2d(
            in_channels=512,
            out_channels=NUM_CLASSES,
            kernel_size=1
        ),
        nn.AdaptiveAvgPool2d((1, 1))
    )

    nn.init.normal_(
        model.classifier[1].weight,
        mean=0.0,
        std=0.01
    )
    nn.init.zeros_(model.classifier[1].bias)

    model.num_classes = NUM_CLASSES
    model = model.to(device)


    def parameter_counts(model):
        total = sum(p.numel() for p in model.parameters())
        trainable = sum(
            p.numel() for p in model.parameters()
            if p.requires_grad
        )
        return total, trainable


    total, trainable = parameter_counts(model)

    print(f"Total parameters: {total:,}")
    print(f"Initially trainable parameters: {trainable:,}")

    with torch.no_grad():
        output = model(images[:2].to(device))

    assert output.shape == (2, NUM_CLASSES)
    print("Output shape:", output.shape)

    criterion = nn.CrossEntropyLoss()

    history = []
    best_val_loss = float("inf")
    BEST_PATH = OUTPUT_DIR / "squeezenet_best_state.pt"


    def run_epoch(loader, optimizer=None):
        training = optimizer is not None
        model.train(training)

        total_loss = 0.0
        total_correct = 0
        total_samples = 0

        for images, labels in tqdm(
            loader,
            leave=False,
            desc="Train" if training else "Validation"
        ):
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            if training:
                optimizer.zero_grad(set_to_none=True)

            with torch.set_grad_enabled(training):
                logits = model(images)
                loss = criterion(logits, labels)

                if training:
                    loss.backward()
                    optimizer.step()

            batch_size = labels.size(0)

            total_loss += loss.item() * batch_size
            total_correct += (
                logits.argmax(dim=1) == labels
            ).sum().item()
            total_samples += batch_size

        return (
            total_loss / total_samples,
            total_correct / total_samples
        )


    def fit_stage(stage_name, epochs, optimizer):
        nonlocal best_val_loss

        for _ in range(epochs):
            epoch = len(history) + 1

            if device.type == "cuda":
                torch.cuda.synchronize()

            start = time.perf_counter()

            train_loss, train_acc = run_epoch(
                train_loader, optimizer
            )
            val_loss, val_acc = run_epoch(val_loader)

            if device.type == "cuda":
                torch.cuda.synchronize()

            elapsed = time.perf_counter() - start

            history.append({
                "epoch": epoch,
                "stage": stage_name,
                "train_loss": train_loss,
                "val_loss": val_loss,
                "train_accuracy": train_acc,
                "val_accuracy": val_acc,
                "epoch_seconds_including_validation": elapsed
            })

            if val_loss < best_val_loss:
                best_val_loss = val_loss

                # Save weights only, without optimizer state.
                state = {
                    key: value.detach().cpu().clone()
                    for key, value in model.state_dict().items()
                }
                torch.save(state, BEST_PATH)

            pd.DataFrame(history).to_csv(
                OUTPUT_DIR / "training_history.csv",
                index=False
            )

            print(
                f"Epoch {epoch:02d} | {stage_name} | "
                f"train loss={train_loss:.4f}, "
                f"train acc={train_acc:.4f} | "
                f"val loss={val_loss:.4f}, "
                f"val acc={val_acc:.4f} | "
                f"{elapsed:.1f}s"
            )

    head_optimizer = torch.optim.Adam(
        model.classifier.parameters(),
        lr=1e-3
    )

    fit_stage(
        stage_name="classifier_training",
        epochs=args.head_epochs,
        optimizer=head_optimizer
    )

    # Start fine-tuning from the best classifier-stage checkpoint.
    model.load_state_dict(
        torch.load(
            BEST_PATH,
            map_location=device,
            weights_only=True
        )
    )

    for parameter in model.features.parameters():
        parameter.requires_grad = True

    fine_tune_optimizer = torch.optim.Adam(
        [
            {
                "params": model.features.parameters(),
                "lr": 1e-5
            },
            {
                "params": model.classifier.parameters(),
                "lr": 1e-4
            }
        ]
    )

    total, trainable = parameter_counts(model)

    print(f"Total parameters: {total:,}")
    print(f"Trainable during fine-tuning: {trainable:,}")

    fit_stage(
        stage_name="fine_tuning",
        epochs=args.fine_tune_epochs,
        optimizer=fine_tune_optimizer
    )

    history_df = pd.DataFrame(history)

    fig, axes = plt.subplots(1, 2, figsize=(13, 4))

    axes[0].plot(
        history_df["epoch"],
        history_df["train_loss"],
        label="Training"
    )
    axes[0].plot(
        history_df["epoch"],
        history_df["val_loss"],
        label="Validation"
    )
    axes[0].set_title("SqueezeNet loss")
    axes[0].set_ylabel("Cross-entropy loss")

    axes[1].plot(
        history_df["epoch"],
        history_df["train_accuracy"],
        label="Training"
    )
    axes[1].plot(
        history_df["epoch"],
        history_df["val_accuracy"],
        label="Validation"
    )
    axes[1].set_title("SqueezeNet accuracy")
    axes[1].set_ylabel("Accuracy")

    for ax in axes:
        ax.axvline(
            args.head_epochs + 0.5,
            color="gray",
            linestyle="--",
            label="Fine-tuning begins"
        )
        ax.set_xlabel("Epoch")
        ax.legend()
        ax.grid(alpha=0.3)

    plt.tight_layout()
    plt.savefig(
        OUTPUT_DIR / "training_curves.png",
        dpi=200,
        bbox_inches="tight"
    )
    if args.show_plots:
        plt.show()
    else:
        plt.close(fig)

    best_row = history_df.loc[
        history_df["val_loss"].idxmin()
    ]

    print("Selected checkpoint:")
    print(best_row[["epoch", "stage", "val_loss", "val_accuracy"]])
    model.load_state_dict(
        torch.load(
            BEST_PATH,
            map_location=device,
            weights_only=True
        )
    )
    model.eval()

    y_true = []
    y_pred = []
    test_loss_sum = 0.0

    with torch.no_grad():
        for images, labels in tqdm(
            test_loader,
            desc="Test evaluation"
        ):
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            logits = model(images)
            loss = criterion(logits, labels)
            predictions = logits.argmax(dim=1)

            test_loss_sum += loss.item() * labels.size(0)

            y_true.extend(labels.cpu().tolist())
            y_pred.extend(predictions.cpu().tolist())

    test_accuracy = accuracy_score(y_true, y_pred)
    test_loss = test_loss_sum / len(test_dataset)

    report = classification_report(
        y_true,
        y_pred,
        labels=list(range(NUM_CLASSES)),
        target_names=class_names,
        output_dict=True,
        zero_division=0
    )

    print(f"Test loss: {test_loss:.4f}")
    print(f"Test accuracy: {test_accuracy * 100:.2f}%")

    print(classification_report(
        y_true,
        y_pred,
        labels=list(range(NUM_CLASSES)),
        target_names=class_names,
        digits=4,
        zero_division=0
    ))

    pd.DataFrame(report).transpose().to_csv(
        OUTPUT_DIR / "classification_report.csv"
    )

    # Save predictions with the corresponding image paths.
    predictions_df = test_dataset.frame.copy()
    predictions_df["predicted_label"] = y_pred
    predictions_df["predicted_class"] = [
        class_names[label] for label in y_pred
    ]

    predictions_df.to_csv(
        OUTPUT_DIR / "test_predictions.csv",
        index=False
    )

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=list(range(NUM_CLASSES))
    )

    fig, ax = plt.subplots(figsize=(10, 9))

    display = ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=class_names
    )

    display.plot(
        ax=ax,
        cmap="Blues",
        xticks_rotation=90,
        colorbar=False
    )

    ax.set_title("SqueezeNet — EuroSAT test confusion matrix")

    plt.tight_layout()
    plt.savefig(
        OUTPUT_DIR / "confusion_matrix.png",
        dpi=200,
        bbox_inches="tight"
    )
    if args.show_plots:
        plt.show()
    else:
        plt.close(fig)

    pd.DataFrame(
        cm,
        index=class_names,
        columns=class_names
    ).to_csv(OUTPUT_DIR / "confusion_matrix.csv")
    total_params, trainable_params = parameter_counts(model)

    file_bytes = BEST_PATH.stat().st_size

    # Decimal MB, explicitly labelled.
    model_size_mb = file_bytes / 1_000_000

    # Theoretical float32 parameter storage.
    fp32_weights_mb = total_params * 4 / 1_000_000

    import hashlib

    summary = {
        "seed": SEED,
        "split_manifest_sha256": hashlib.sha256(args.splits.read_bytes()).hexdigest(),
        "class_mapping_sha256": hashlib.sha256(args.classes.read_bytes()).hexdigest(),
        "model": "SqueezeNet 1.1",
        "pretrained_weights": str(weights),
        "dataset": "EuroSAT RGB",
        "input_resolution": "64x64",
        "total_parameters": total_params,
        "trainable_parameters_during_fine_tuning": trainable_params,
        "weights_checkpoint_size_MB": model_size_mb,
        "estimated_FP32_parameter_storage_MB": fp32_weights_mb,
        "test_loss": test_loss,
        "test_accuracy": test_accuracy,
        "macro_precision": report["macro avg"]["precision"],
        "macro_recall": report["macro avg"]["recall"],
        "macro_f1": report["macro avg"]["f1-score"],
        "training_epochs": len(history_df),
        "selected_epoch": int(best_row["epoch"]),
        "mean_epoch_seconds_including_validation": float(
            history_df[
                "epoch_seconds_including_validation"
            ].mean()
        )
    }



    summary_df = pd.DataFrame([summary])
    print(summary_df.transpose().to_string(header=False))

    summary_df.to_csv(
        OUTPUT_DIR / "model_summary.csv",
        index=False
    )

    with open(OUTPUT_DIR / "model_summary.json", "w") as f:
        json.dump(summary, f, indent=2)

    with open(OUTPUT_DIR / "class_names.json", "w") as f:
        json.dump(class_names, f, indent=2)

    manifest.to_csv(
        OUTPUT_DIR / "eurosat_splits.csv",
        index=False
    )

    print(f"Total parameters: {total_params:,}")
    print(f"Checkpoint size: {model_size_mb:.3f} MB")
    print(f"Test accuracy: {test_accuracy * 100:.2f}%")


def main():
    train(parse_args())


if __name__ == "__main__":
    main()
